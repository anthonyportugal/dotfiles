#!/usr/bin/env bash
# Generated ~/.config/mimeapps.list, sourced by the desktop hooks. The repo
# keeps only defaults: its keys always win, every other entry the file already
# had (associations registered by applications, other sections) is kept.
# Applications write to this file, so it is never a link into the checkout.

MIMEAPPS_DEFAULTS="$LAYER_DIR/mimeapps/defaults.list"

# Prints defaults file $1 merged over the existing file $2 (may be empty).
merge_mimeapps() {
  awk '
    function add_section(name) {
      if (!(name in seen_section)) { seen_section[name] = 1; order[++sections] = name }
    }
    /^[[:space:]]*(#|$)/ { next }
    /^\[.*\]$/ { section = $0; add_section(section); next }
    !/=/ || section == "" { next }
    {
      key = substr($0, 1, index($0, "=") - 1)
      id = section SUBSEP key
      if (FNR == NR) {
        repo[id] = 1
        lines[section, ++count[section]] = $0
      } else if (!(id in repo) && !(id in kept)) {
        kept[id] = 1
        lines[section, ++count[section]] = $0
      }
    }
    END {
      print "# Generated by dotfiles from layers/desktop/mimeapps/defaults.list."
      print "# Its keys are rewritten on every apply; other entries are kept."
      for (s = 1; s <= sections; s++) {
        if (count[order[s]] == 0) continue
        if (printed++) print ""
        print order[s]
        for (i = 1; i <= count[order[s]]; i++) print lines[order[s], i]
      }
    }' "$1" "$2"
}

# Writes the merged file into target $1, replacing a symlink left by Stow.
# An unchanged file is not rewritten.
apply_mimeapps() {
  local file="$1/.config/mimeapps.list" existing='/dev/null' merged

  if [[ -f "$file" && -r "$file" ]]; then
    existing=$file
  fi
  mkdir -p -- "$1/.config"
  merged=$(mktemp "$1/.config/.mimeapps.list.XXXXXX")
  if ! merge_mimeapps "$MIMEAPPS_DEFAULTS" "$existing" > "$merged"; then
    rm -f -- "$merged"
    return 1
  fi
  if [[ -f "$file" && ! -L "$file" ]] && cmp -s -- "$merged" "$file"; then
    rm -f -- "$merged"
    return 0
  fi
  chmod 644 -- "$merged"
  mv -fT -- "$merged" "$file"
  info "mimeapps.list generado: $file"
}

# Warns when the file is missing, still a link, or a repo key drifted. It only
# reports: the next apply restores the repo keys.
check_mimeapps() {
  local file="$TARGET_DIR/.config/mimeapps.list" drifted

  if [[ ! -e "$file" ]]; then
    warn "falta $file; ejecute bootstrap para generarlo"
    return 0
  fi
  if [[ -L "$file" ]]; then
    warn "$file sigue siendo un enlace; ejecute bootstrap para generarlo"
    return 0
  fi
  # Repo keys whose value differs from, or is missing in, the file.
  drifted=$(awk '
    /^\[.*\]$/ { section = $0; next }
    !/=/ { next }
    { key = substr($0, 1, index($0, "=") - 1); id = section SUBSEP key }
    FNR == NR { want[id] = $0; name[id] = key; next }
    id in want { found[id] = 1; if (want[id] != $0) bad[id] = 1 }
    END {
      for (id in want) if (!(id in found) || (id in bad)) {
        printf "%s%s", sep, name[id]; sep = ", "
      }
    }' "$MIMEAPPS_DEFAULTS" "$file")
  if [[ -n "$drifted" ]]; then
    warn "$file difiere del repo en $drifted; el próximo apply lo restaura"
  fi
}
